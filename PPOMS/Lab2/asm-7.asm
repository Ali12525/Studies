ORG 0000H

; Точка входа программы
START:
    MOV R0, #058H        ; Адрес массива в ОЗУ, куда будем копировать данные из таблицы
    MOV R1, #0AH         ; Количество элементов массива = 10
    MOV DPTR, #DATA_TABLE ; Указатель на таблицу исходных данных

; Заполнение массива
FILL:
    CLR A                 ; Очистка аккумулятора перед загрузкой
    MOVC A, @A+DPTR       ; Чтение байта из таблицы по DPTR (код из памяти программы)
    MOV @R0, A            ; Сохраняем значение в массив в ОЗУ
    INC DPTR              ; Переход к следующему элементу таблицы
    INC R0                ; Переход к следующей ячейке массива в ОЗУ
    DJNZ R1, FILL         ; Повторяем цикл, пока не скопируем все элементы

; Инициализация перед поиском
    MOV R0, #058H         ; Сброс указателя на начало массива
    MOV R1, #0AH          ; Количество элементов для обработки
    MOV B, #00H           ; Флаг "найдено" = 0, пока отрицательных чисел < -10 нет

; Основной цикл поиска минимального отрицательного числа (< -10)
NEXT:
    MOV A, @R0             ; Загружаем текущий элемент массива

    ; Проверка: отрицательное число? (старший бит = 1)
    JB ACC.7, NEGATIVE
    SJMP SKIP

NEGATIVE:
    ; Проверка: меньше ли -10 (0F6h = -10 в десятичной системе)
    MOV A, @R0
    CLR C
    SUBB A, #0F6H          ; Вычисляем A - (-10)
    JNC SKIP               ; Если A >= -10 → пропускаем

    ; Если первый найденный элемент — запоминаем
    MOV A, B    
    CJNE A, #00H, COMPARE  ; Если уже найдено предыдущее значение, сравниваем
    MOV A, @R0
    MOV R3, A               ; Сохраняем первый подходящий элемент в R3
    MOV B, #01H             ; Флаг "найдено" = 1
    SJMP SKIP

COMPARE:
    ; Проверка: текущий элемент меньше, чем уже найденный? (ищем максимум среди отрицательных)
    MOV A, R3
    CLR C
    SUBB A, @R0
    JNC SKIP               ; Если текущий элемент <= найденного → пропустить

NEWMAX:
    MOV A, @R0
    MOV R3, A              ; Обновляем максимальный элемент среди отрицательных

SKIP:
    INC R0
    DEC R1
    JNZ NEXT               ; Переходим к следующему элементу массива

; Проверка результата поиска
CHECK_RES:
    MOV A, B
    CJNE A, #01H, ERR       ; Если подходящий элемент не найден, переходим в ERR

GOOD:
    SETB P3.3
    SETB P3.4
    MOV P1, #11000010B      ; Отобразить символ "G" на 7-сегментном индикаторе
    SJMP GOOD               ; Зациклить индикатор "G"

ERR:
    SETB P3.3
    SETB P3.4
    MOV P1, #10000110B      ; Отобразить символ "E" на 7-сегментном индикаторе
    SJMP ERR                ; Зациклить индикатор "E"

; Таблица данных
ORG 0100H
DATA_TABLE:
    DB 021H   ; 33          (положительное)
    DB 0F9H   ; -7          (отрицательное > -10)
    DB 0F9H   ; -24         (отрицательное < -10)
    DB 0F9H   ; 122         (положительное)
    DB 0F9H   ; -46         (отрицательное < -10)
    DB 0F9H   ; -11         (отрицательное < -10)
    DB 0F9H   ; -80         (отрицательное < -10)
    DB 0FEH   ; -2          (отрицательное > -10)
    DB 019H   ; 25          (положительное)
    DB 0F9H   ; -16         (отрицательное < -10)

END

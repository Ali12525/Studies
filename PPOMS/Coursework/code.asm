START:
; Ввод 10 значений из ЦАП (DAC)
            MOV R0, #58h      ; R0 = 0x58 
            MOV R1, #10       ; R1 = 10

IN_LOOP:
            LCALL SWITCH0     ; Ждём нажатия и отпускания кнопки (P2.0)
            LCALL FUNCTION    ; Читаем значение с ЦАП и сохраняем в буфер
            INC R0            ; Увеличиваем адрес буфера для следующего значения
            DJNZ R1, IN_LOOP  ; Уменьшаем счётчик, если не 0 — повторяем цикл

; ----- Обработка массива по принципу LIFO (стек) -----
            MOV R0, #61h      ; R0 = 0x61 (указывает на конец буфера данных)
            MOV R1, #10       ; R1 = 10 (счётчик для обработки 10 значений)
            MOV R2, #00h      ; R2 = 0 (здесь будет максимальное отрицательное число)
            MOV R3, #00h      ; R3 = 0 (флаг: 0 — максимум не найден, 1 — найден)

PROC_LOOP:
            MOV A, @R0        ; Загружаем в A текущее значение из буфера
            JNB ACC.7, NEXT_ELEM ; Если старший бит = 0 (число положительное), пропускаем

            ; Проверяем, является ли число -10 (0xF6 в доп коде)
            CJNE A, #0F6h, CHK_LT ; Если не равно -10, переходим к CHK_LT
            SJMP NEXT_ELEM        ; Если равно -10, пропускаем (не учитываем)
CHK_LT:
            JNC NEXT_ELEM     ; Если A >= 0xF6 (т.е. -10 или больше), пропускаем

            ; Здесь обрабатываем отрицательные числа меньше -10
            MOV R4, A         ; Сохраняем текущее число в R4
            MOV A, R3         ; Проверяем флаг нахождения максимума
            JNZ COMPARE       ; Если максимум уже был, переходим к сравнению
            ; Иначе инициализируем максимум текущим числом
            MOV A, R4
            MOV R2, A         ; Сохраняем текущее число как максимальное
            MOV R3, #01h      ; Устанавливаем флаг, что максимум найден
            SJMP NEXT_ELEM    ; Переходим к следующему элементу

COMPARE:
            MOV A, R2         ; Загружаем текущий максимум
            CLR C             ; Сбрасываем флаг переноса
            SUBB A, R4        ; Вычитаем текущее число (R2 - R4)
            JNC NEXT_ELEM     ; Если R2 >= R4 (текущий максимум больше или равен), пропускаем
            MOV A, R4         ; Иначе обновляем максимум
            MOV R2, A         ; Сохраняем новое максимальное число

NEXT_ELEM:
            DEC R0            ; Уменьшаем адрес (двигаемся к началу буфера)
            DJNZ R1, PROC_LOOP ; Уменьшаем счётчик, если не 0 — повторяем цикл

; ----- Вывод результата -----
            MOV A, R2         ; Загружаем найденный максимум в A
            JZ ERR            ; Если максимум = 0 (не было отрицательных чисел < -10), переходим к ERR
            LCALL OUT_RESULT  ; Выводим результат на индикатор

stop:       SJMP stop         ; Бесконечный цикл (остановка программы)

; ----- Подпрограмма ожидания кнопки (P2.0) -----
SWITCH0:
W1:         JB  P2.0, W1     ; Ждём, пока кнопка не будет нажата
W2:         JNB P2.0, W2     ; Ждём, пока кнопка не будет отпущена
            RET               ; Возврат из подпрограммы

; ----- Подпрограмма чтения значения с ЦАП -----
FUNCTION:
            CLR P0.7          ; Сигнал начала преобразования для ЦАП

            MOV R2, #8        ; R2 = 8 (счётчик битов для последовательного чтения)
            MOV R3, #80h      ; R3 = 0x80 (маска для старшего бита)
            MOV R4, #00h      ; R4 = 0 (здесь будет накопленное значение)

FLOOP:
            MOV A, R4         ; Загружаем текущее значение
            ORL A, R3         ; Устанавливаем текущий бит из маски
            MOV P1, A         ; Выводим на ЦАП для установки бита
            JB  P3.7, SAVE    ; Если P3.7 = 1 (бит установлен), сохраняем его
            SJMP NEXT         ; Иначе переходим к следующему биту
SAVE:
            MOV R4, A         ; Сохраняем значение с установленным битом
NEXT:
            MOV A, R3         ; Сдвигаем маску вправо для следующего бита
            RR  A
            MOV R3, A
            DJNZ R2, FLOOP    ; Повторяем для всех 8 битов

            ; Проверяем, не достигнуто ли максимальное значение
            MOV P1, R4        ; Выводим итоговое значение на ЦАП
            JB  P3.7, UP      ; Если P3.7 = 1 (значение слишком велико), увеличиваем

WRITE_ADC:  MOV @R0, P1       ; Сохраняем значение из P1 в буфер по адресу R0
            RET               ; Возврат из подпрограммы

UP:
            ; Проверяем, не равно ли значение 0xFF (максимум)
            CJNE R4, #0FFh, NMAX ; Если не равно, увеличиваем
            SJMP WRITE_ADC       ; Иначе сохраняем как есть
NMAX:
            INC R4            ; Увеличиваем значение на 1
            MOV P1, R4        ; Выводим новое значение на ЦАП
            SJMP WRITE_ADC    ; Сохраняем в буфер

; ----- Подпрограмма вывода результата на 7-сегментный индикатор -----
OUT_RESULT: 
            MOV A, R2         ; Загружаем результат (максимальное число)
            MOV P1, A         ; Выводим на порт P1
            CALL SWITCH0      ; Ждём нажатия кнопки
            MOV P1, #0FFH     ; Гасим индикатор (все сегменты выключены)
            
            ; Выводим старшую тетраду (старший полубайт)
            SWAP A            ; Меняем тетрады местами
            ANL A, #0Fh       ; Оставляем только младшую тетраду
            MOV DPTR, #HEX_TAB ; Загружаем адрес таблицы преобразования
            MOVC A, @A+DPTR   ; Преобразуем в 7-сегментный код
            SETB P0.7         ; Включаем индикатор
            SETB P3.4         ; Включаем разряд индикатора
            SETB P3.3         ; Включаем разряд индикатора
            MOV P1, A         ; Выводим код символа на индикатор
            MOV P1, #0FFH     ; Гасим индикатор
            
            ; Выводим младшую тетраду (младший полубайт)
            MOV A, R2         ; Снова загружаем результат
            ANL A, #0Fh       ; Оставляем только младшую тетраду
            MOV DPTR, #HEX_TAB ; Адрес таблицы преобразования
            MOVC A, @A+DPTR   ; Преобразуем в 7-сегментный код
            CLR P3.3          
            MOV P1, A         ; Выводим код символа на индикатор
            MOV P1, #0FFH     ; Гасим индикатор
            CALL SWITCH0      ; Ждём нажатия кнопки
            CLR P0.7          ; Выключаем индикатор
            SJMP OUT_RESULT   ; Повторяем вывод
            RET              

; Таблица преобразования цифр в 7-сегментный код (общий анод)
HEX_TAB:
    DB 0C0h ; 0
    DB 0F9h ; 1
    DB 0A4h ; 2
    DB 0B0h ; 3
    DB 099h ; 4
    DB 092h ; 5
    DB 082h ; 6
    DB 0F8h ; 7
    DB 080h ; 8
    DB 090h ; 9
    DB 088h ; A
    DB 083h ; b
    DB 0C6h ; C
    DB 0A1h ; d
    DB 086h ; E
    DB 08Eh ; F

; ----- Подпрограмма вывода ошибки (если нет подходящих чисел) -----
ERR:
    SETB P0.7        ; Включаем индикатор
    SETB P3.3        ; Включаем разряд индикатора
    SETB P3.4        ; Включаем разряд индикатора
    MOV P1, #10000110B ; Выводим символ 'E' (ошибка)
    MOV P1, #0FFH     ; Гасим индикатор
    CLR P3.3          ; Отключаем разряд индикатора
    MOV P1, #10101111B ; Выводим символ 'r' (ошибка)
    MOV P1, #0FFH     ; Гасим индикатор
    SETB P3.3         ; Включаем разряд индикатора
    CLR P3.4          ; Отключаем разряд индикатора
    MOV P1, #10101111B ; Выводим символ 'r' (ошибка)
    MOV P1, #0FFh     ; Гасим индикатор
    JMP ERR           ; Бесконечный цикл (мигание "Err")
    
    END               ; Конец программы